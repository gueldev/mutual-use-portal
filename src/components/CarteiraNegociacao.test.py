"""Regressão: salvar negociação exige clique, não ativação pelo teclado."""
import unittest
from playwright.sync_api import sync_playwright, expect


class SalvarNegociacaoTest(unittest.TestCase):
    def test_salvar_somente_por_clique(self):
        with sync_playwright() as p:
            browser = p.chromium.launch(headless=True)
            page = browser.new_page(viewport={"width": 1280, "height": 1800})
            page.goto("http://localhost:8080")
            page.wait_for_timeout(1500)
            page.get_by_role("button", name="Carteira", exact=True).click()
            page.get_by_role("button", name="Carteira de Negociação", exact=True).click()
            page.get_by_placeholder("10 dígitos").wait_for()
            page.get_by_placeholder("000.000.000-00 ou 00.000.000/0000-00").fill("52998224725")
            page.get_by_placeholder("10 dígitos").fill("1234567890")
            for label, value in [("Nome do Parceiro", "Parceiro"), ("Plaqueta", "12345"), ("Razão Social", "Empresa")]:
                page.locator("div.flex.flex-col.gap-1\\.5").filter(
                    has=page.locator("label", has_text=label)
                ).locator("input").fill(value)
            confirmation = page.get_by_text("Dados do cliente validados.", exact=True)
            save = page.get_by_role("button", name="Salvar", exact=True)
            page.get_by_placeholder("10 dígitos").press("Enter")
            self.assertFalse(confirmation.is_visible())
            save.press("Enter")
            self.assertFalse(confirmation.is_visible())
            save.press("Space")
            self.assertFalse(confirmation.is_visible())
            save.click()
            self.assertFalse(confirmation.is_visible())
            page.get_by_text("Informe o município/local de prestação.", exact=True).wait_for()
            page.get_by_text("Selecione o setor.", exact=True).wait_for()
            page.get_by_text("Selecione o status do projeto.", exact=True).wait_for()
            page.get_by_role("combobox", name="Município/Local de prestação", exact=True).fill("Recife")
            page.get_by_role("button", name="Recife", exact=True).click()
            page.get_by_role("combobox", name="Setor", exact=True).click()
            page.get_by_role("option", name="Norte", exact=True).click()
            page.get_by_role("combobox", name="Status Projeto", exact=True).click()
            page.get_by_role("option", name="Aguardando", exact=True).click()
            page.get_by_role("textbox", name="Nº Notificação", exact=True).fill("TESTE-123")
            page.get_by_role("button", name="Adicionar município", exact=False).click()
            page.get_by_role("textbox", name="Buscar município para adicionar", exact=True).fill("Recife")
            page.get_by_role("checkbox", name="Recife", exact=True).click()
            page.get_by_role("button", name="Adicionar município", exact=False).click()
            page.get_by_role("textbox", name="Preço do Ponto (R$) — Recife", exact=True).fill("20")
            page.get_by_role("spinbutton", name="Qtd Pontos Censo — Recife", exact=True).fill("8")
            page.get_by_role("spinbutton", name="Qtd Pontos à Revelia — Recife", exact=True).fill("10")
            page.get_by_role("textbox", name="Data Início — Recife", exact=True).fill("01/01/2026")
            page.get_by_role("textbox", name="Data Fim — Recife", exact=True).fill("10/05/2026")
            page.get_by_role("button", name="Alterar Implemento Calculado (R$) — Recife", exact=True).click()
            page.get_by_role("spinbutton", name="Implemento Calculado (R$) — Recife", exact=True).fill("350")
            page.get_by_role("button", name="Concluir edição de Implemento Calculado (R$) — Recife", exact=True).click()
            save.click()
            confirmation.wait_for()
            self.assertTrue(confirmation.is_visible())
            self.assertEqual(page.get_by_placeholder("10 dígitos").input_value(), "")
            page.get_by_role("button", name="Base da carteira", exact=True).click()
            page.get_by_role("cell", name="TESTE-123", exact=True).wait_for()
            self.assertEqual(page.locator("tbody tr").count(), 1)
            search = page.get_by_role("textbox", name="Pesquisar carteira", exact=True)
            search.fill("123")
            self.assertEqual(page.locator("tbody tr").count(), 1)
            search.fill("inexistente")
            self.assertEqual(page.locator("tbody tr").count(), 0)
            search.fill("")
            page.get_by_role("button", name="Editar", exact=True).click()
            page.get_by_placeholder("10 dígitos").wait_for()
            expect(page.get_by_role("textbox", name="Nº Notificação", exact=True)).to_have_value("TESTE-123")
            self.assertEqual(page.get_by_placeholder("10 dígitos").input_value(), "1234567890")
            self.assertIn("350", page.get_by_role("textbox", name="Implemento Calculado (R$) — Recife", exact=True).input_value())
            page.get_by_role("textbox", name="Nº Notificação", exact=True).fill("TESTE-EDITADO")
            page.get_by_role("button", name="Salvar", exact=True).click()
            page.screenshot(path="/tmp/browser/base-carteira-edicao.png")
            page.get_by_role("cell", name="TESTE-EDITADO", exact=True).wait_for()
            self.assertEqual(page.locator("tbody tr").count(), 1)
            page.reload()
            page.wait_for_timeout(1500)
            page.get_by_role("button", name="Carteira", exact=True).click()
            page.get_by_role("button", name="Base da carteira", exact=True).click()
            page.get_by_role("cell", name="TESTE-EDITADO", exact=True).wait_for()
            browser.close()


if __name__ == "__main__":
    unittest.main()